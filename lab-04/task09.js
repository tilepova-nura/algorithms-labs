// Задача 9. Рекурсивное решение головоломки «Ханойская башня».
// Есть три стержня и n дисков разного размера на первом стержне.
// Нужно перенести все диски на третий стержень. За ход переносится один диск,
// и нельзя класть больший диск на меньший.
//
// Рекурсивная идея, чтобы перенести n дисков с from на to:
//   1) перенести верхние n − 1 дисков с from на вспомогательный стержень via;
//   2) перенести самый большой диск с from на to;
//   3) перенести n − 1 дисков с via на to.
// Базовый случай: 0 дисков — ничего делать не нужно.

const { askInteger, close } = require('./input');

let moves = 0;

function hanoi(n, from, to, via) {
  if (n === 0) {
    return;
  }
  hanoi(n - 1, from, via, to);
  moves++;
  console.log(`Ход ${moves}: диск ${n} со стержня ${from} на стержень ${to}`);
  hanoi(n - 1, via, to, from);
}

async function main() {
  const n = await askInteger('Количество дисков (от 1 до 10): ', 1, 10);

  hanoi(n, 1, 3, 2);
  console.log(`Всего ходов: ${moves} (это 2^${n} − 1)`);
  close();
}

main();
