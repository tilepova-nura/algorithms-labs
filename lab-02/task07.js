// Задача 7. Дан номер дня (1–31) и номер месяца (1–12).
// Вывести дату в виде текста, например «пятое января».

const { askInteger, close } = require('./input');

// Порядковые числительные среднего рода: 1 → «первое»
const DAY_UNITS = ['', 'первое', 'второе', 'третье', 'четвертое', 'пятое',
  'шестое', 'седьмое', 'восьмое', 'девятое'];
const DAY_TEENS = ['десятое', 'одиннадцатое', 'двенадцатое', 'тринадцатое',
  'четырнадцатое', 'пятнадцатое', 'шестнадцатое', 'семнадцатое',
  'восемнадцатое', 'девятнадцатое'];

const MONTHS = ['января', 'февраля', 'марта', 'апреля', 'мая', 'июня', 'июля',
  'августа', 'сентября', 'октября', 'ноября', 'декабря'];

// Сколько дней в каждом месяце (в феврале 29, чтобы принять и високосный год)
const DAYS_IN_MONTH = [31, 29, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];

function dayToText(day) {
  if (day < 10) return DAY_UNITS[day];
  if (day < 20) return DAY_TEENS[day - 10];
  if (day === 20) return 'двадцатое';
  if (day < 30) return 'двадцать ' + DAY_UNITS[day - 20];
  if (day === 30) return 'тридцатое';
  return 'тридцать ' + DAY_UNITS[day - 30];
}

async function main() {
  const day = await askInteger('День (1–31): ', 1, 31);
  const month = await askInteger('Месяц (1–12): ', 1, 12);

  if (day > DAYS_IN_MONTH[month - 1]) {
    console.log(`В этом месяце нет ${day}-го числа.`);
  } else {
    console.log(`${dayToText(day)} ${MONTHS[month - 1]}`);
  }
  close();
}

main();
