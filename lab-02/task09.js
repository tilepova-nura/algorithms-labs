// Задача 9. Дано целое число в диапазоне 100–999.
// Вывести его словами, например: 256 → «двести пятьдесят шесть».
// Делим число на сотни, десятки и единицы и для каждой части берём слово из массива.

const { askInteger, close } = require('./input');

const HUNDREDS = ['', 'сто', 'двести', 'триста', 'четыреста', 'пятьсот',
  'шестьсот', 'семьсот', 'восемьсот', 'девятьсот'];
const TENS = ['', '', 'двадцать', 'тридцать', 'сорок', 'пятьдесят',
  'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто'];
const TEENS = ['десять', 'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать',
  'пятнадцать', 'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать'];
const UNITS = ['', 'один', 'два', 'три', 'четыре', 'пять', 'шесть', 'семь', 'восемь', 'девять'];

async function main() {
  const n = await askInteger('Число от 100 до 999: ', 100, 999);

  const hundreds = Math.floor(n / 100);  // 256 → 2
  const tens = Math.floor(n / 10) % 10;  // 256 → 5
  const units = n % 10;                  // 256 → 6

  const words = [HUNDREDS[hundreds]];
  if (tens === 1) {
    // числа 10–19 называются одним словом: «четырнадцать»
    words.push(TEENS[units]);
  } else {
    if (tens > 1) words.push(TENS[tens]);
    if (units > 0) words.push(UNITS[units]);
  }

  console.log(words.join(' '));
  close();
}

main();
