// Задача 9. Начальный вклад 1000 руб. Каждый месяц он увеличивается на P процентов
// (0 < P < 25). Определить, через сколько месяцев вклад превысит 1100 руб.,
// и вывести количество месяцев K и итоговый размер вклада S.

const { askNumber, close, round } = require('./input');

async function main() {
  let p;
  do {
    p = await askNumber('P (от 0 до 25, не включая): ');
  } while (p <= 0 || p >= 25);

  let s = 1000;
  let k = 0;
  while (s <= 1100) {
    s += s * p / 100; // начисляем проценты на текущую сумму
    k++;
  }

  console.log(`K = ${k} мес., S = ${round(s)} руб.`);
  close();
}

main();
